import { ShellTomeItem } from "../hooks/useShellData";

export interface TomeParamDefInput {
    name: string;
    label: string;
    type: string;
    placeholder: string;
}

export interface ParsedComposerTomeDraft {
    suggestedName: string;
    suggestedDescription: string;
    suggestedTactic: string;
    cleanedEldritch: string;
    detectedParams: TomeParamDefInput[];
    hadComposerHeader: boolean;
}

export function formatParamLabel(paramName: string): string {
    const cleaned = paramName.trim().replace(/[_-]+/g, " ");
    if (!cleaned) return "";
    return cleaned.charAt(0).toUpperCase() + cleaned.slice(1);
}

/**
 * Parses a script from the Eldritch Composer to extract any `# Tome: ...` metadata header,
 * `input_params = { ... }` mock dictionary block, and `input_params["..."]` references.
 */
export function parseComposerScriptForTome(
    rawCode: string,
    existingTomes: ShellTomeItem[] = []
): ParsedComposerTomeDraft {
    const normalized = rawCode.replace(/\r\n/g, "\n");
    const lines = normalized.split("\n");

    let lineIdx = 0;
    let suggestedName = "";
    let suggestedDescription = "";
    let suggestedTactic = "UNSPECIFIED";
    let hadComposerHeader = false;

    // 1. Check for `# Tome: <Name>` header generated by formatTomeForComposer
    if (lines[lineIdx] && /^#\s*Tome:\s*(.+)$/i.test(lines[lineIdx].trim())) {
        const match = lines[lineIdx].trim().match(/^#\s*Tome:\s*(.+)$/i);
        const rawTomeName = match ? match[1].trim() : "";
        hadComposerHeader = true;
        lineIdx += 1;

        if (rawTomeName) {
            const matchedExisting = existingTomes.find(
                (t) => t.name.trim().toLowerCase() === rawTomeName.toLowerCase()
            );
            if (matchedExisting) {
                suggestedName = `${rawTomeName} (Custom)`;
                if (matchedExisting.tactic) {
                    suggestedTactic = matchedExisting.tactic;
                }
            } else {
                suggestedName = rawTomeName;
            }
        }

        // Optional `# <Description>` line right below `# Tome: <Name>`
        if (
            lines[lineIdx] &&
            lines[lineIdx].trim().startsWith("#") &&
            !/^#\s*Tome:/i.test(lines[lineIdx].trim())
        ) {
            suggestedDescription = lines[lineIdx].trim().replace(/^#+\s*/, "").trim();
            lineIdx += 1;
        }
    }

    // Skip blank lines after header
    while (lineIdx < lines.length && lines[lineIdx].trim() === "") {
        lineIdx += 1;
    }

    const paramsByName = new Map<string, TomeParamDefInput>();

    // 2. Check for leading `input_params = { ... }` mock block
    if (lineIdx < lines.length && /^input_params\s*=\s*\{/.test(lines[lineIdx].trim())) {
        let blockEndIdx = lineIdx;
        let foundClosingBrace = false;

        for (let i = lineIdx; i < lines.length; i++) {
            const trimmed = lines[i].trim();
            if (i > lineIdx) {
                const entryMatch = trimmed.match(
                    /^["']([^"']+)["']\s*:\s*(?:["']([^"']*)["']|([^,#]+?))\s*,?(?:\s*#\s*(.*))?$/
                );
                if (entryMatch) {
                    const paramName = entryMatch[1].trim();
                    const strVal = entryMatch[2] ?? (entryMatch[3] ? entryMatch[3].trim() : "");
                    const commentLabel = entryMatch[4] ? entryMatch[4].trim() : "";
                    if (paramName) {
                        paramsByName.set(paramName, {
                            name: paramName,
                            label: commentLabel || formatParamLabel(paramName),
                            type: "string",
                            placeholder: strVal,
                        });
                    }
                }
            }
            if (trimmed.startsWith("}") || (i === lineIdx && trimmed.endsWith("}"))) {
                blockEndIdx = i;
                foundClosingBrace = true;
                break;
            }
        }

        if (foundClosingBrace) {
            hadComposerHeader = true;
            lineIdx = blockEndIdx + 1;
            while (lineIdx < lines.length && lines[lineIdx].trim() === "") {
                lineIdx += 1;
            }
        }
    }

    const cleanedEldritch = lines.slice(lineIdx).join("\n").trim();

    // 3. Scan the script for `input_params["key"]`, `input_params['key']`, or `input_params.get("key")`
    const bracketRegex = /\binput_params\s*\[\s*["']([^"']+)["']\s*\]/g;
    const getRegex = /\binput_params\s*\.\s*get\s*\(\s*["']([^"']+)["']/g;

    let match: RegExpExecArray | null;
    while ((match = bracketRegex.exec(cleanedEldritch)) !== null) {
        const key = match[1].trim();
        if (key && !paramsByName.has(key)) {
            paramsByName.set(key, {
                name: key,
                label: formatParamLabel(key),
                type: "string",
                placeholder: "",
            });
        }
    }
    while ((match = getRegex.exec(cleanedEldritch)) !== null) {
        const key = match[1].trim();
        if (key && !paramsByName.has(key)) {
            paramsByName.set(key, {
                name: key,
                label: formatParamLabel(key),
                type: "string",
                placeholder: "",
            });
        }
    }

    return {
        suggestedName,
        suggestedDescription,
        suggestedTactic,
        cleanedEldritch: cleanedEldritch || normalized.trim(),
        detectedParams: Array.from(paramsByName.values()),
        hadComposerHeader,
    };
}

export function serializeTomeParamDefs(params: TomeParamDefInput[]): string {
    const valid = params
        .map((p) => ({
            name: p.name.trim(),
            label: (p.label || formatParamLabel(p.name)).trim(),
            type: (p.type || "string").trim(),
            placeholder: (p.placeholder || "").trim(),
        }))
        .filter((p) => p.name.length > 0);

    if (valid.length === 0) {
        return "[]";
    }
    return JSON.stringify(valid);
}

